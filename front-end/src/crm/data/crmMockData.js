export function formatCompactMAD(amount, lang = 'en') {
  if (amount === null || amount === undefined || isNaN(amount)) return '0 MAD'
  const isAr = lang === 'ar'
  const abs = Math.abs(amount)
  
  if (abs >= 1_000_000_000) {
    const val = (amount / 1_000_000_000).toFixed(1).replace(/\.0$/, '')
    return isAr ? `${val} مليار درهم` : `${val}B MAD`
  }
  if (abs >= 1_000_000) {
    const val = (amount / 1_000_000).toFixed(1).replace(/\.0$/, '')
    return isAr ? `${val} مليون درهم` : `${val}M MAD`
  }
  if (abs >= 1_000) {
    const val = (amount / 1_000).toFixed(1).replace(/\.0$/, '')
    return isAr ? `${val} ألف درهم` : `${val}K MAD`
  }
  return isAr ? `${amount} درهم` : `${amount} MAD`
}
